"""Write runtime/kernel/import_stubs.cpp: a logging stub for every kernel/XAM
import the recompiled code references that the runtime doesn't implement yet.

    python3 scripts/gen_import_stubs.py                  # Most Wanted's
    SB_GAME=carbon python3 scripts/gen_import_stubs.py   # Carbon's

Import names come from ppc/ppc_recomp_shared.h (XenonRecomp output). An import
counts as implemented if any other runtime source defines it with PPC_FUNC,
GUEST_FUNCTION_HOOK or GUEST_FUNCTION_STUB.

SB_GAME=carbon reads ppc-carbon/ and writes runtime/kernel/import_stubs_carbon.cpp
(built only for Carbon): stubs for the Carbon imports that are neither
implemented nor already stubbed in import_stubs.cpp, which every build has.
Rerun both after implementing an import.
"""
import os
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE_OUT = ROOT / 'runtime/kernel/import_stubs.cpp'
GAME = os.environ.get('SB_GAME', 'mw')
if GAME == 'carbon':
    PPC, OUT = ROOT / 'ppc-carbon', ROOT / 'runtime/kernel/import_stubs_carbon.cpp'
elif GAME == 'mw':
    PPC, OUT = ROOT / 'ppc', BASE_OUT
else:
    raise SystemExit(f'SB_GAME={GAME}: mw or carbon')

imports = sorted(set(re.findall(r'PPC_EXTERN_FUNC\(__imp__(\w+)\)', (PPC / 'ppc_recomp_shared.h').read_text())))
implemented = set()
for src in (ROOT / 'runtime').rglob('*.cpp'):
    if src in (BASE_OUT, OUT):
        continue
    if src.name == 'import_stubs_carbon.cpp':
        continue
    implemented |= set(re.findall(r'(?:PPC_FUNC|GUEST_FUNCTION_HOOK|GUEST_FUNCTION_STUB)\(\s*__imp__(\w+)', src.read_text()))
# Carbon's builds also have Most Wanted's stub file: only what it lacks goes here.
already = set(re.findall(r'PPC_FUNC\(__imp__(\w+)\)', BASE_OUT.read_text())) if OUT != BASE_OUT else set()

missing = [n for n in imports if n not in implemented and n not in already]
lines = [
    '// Generated by scripts/gen_import_stubs.py. Do not edit; implement the import',
    '// elsewhere in runtime/ and rerun the script.',
    '// SpeedBreaker runtime. GPL-3.0-or-later (see COPYING).',
    (f'// {len(imports)} imports: {len(implemented & set(imports))} implemented, {len(missing)} stubbed.' if OUT == BASE_OUT else
     f'// NFS: Carbon (SB_GAME=carbon, built only for it): {len(imports)} imports, {len(implemented & set(imports))} implemented, '
     f'{len(already & set(imports))} stubbed in import_stubs.cpp, these {len(missing)} here.'),
    '#include "../stdafx.h"',
    '#include "unimplemented.h"',
    '',
]
lines += [f'PPC_FUNC(__imp__{n}) {{ UnimplementedImport("{n}", ctx, base); }}' for n in missing]
OUT.write_text('\n'.join(lines) + '\n')
print(f'{OUT.relative_to(ROOT)}: {len(imports)} imports, {len(implemented & set(imports))} implemented, {len(missing)} stubbed here')
